#!/usr/bin/env python3
"""
Claude Code Agent Logger Hook
Logs all AI agent actions to _Agent Logs/ folder in JSONL format.
Pure Python — no external dependencies.
"""

import json
import os
import sys
from datetime import datetime, timezone

# --- Configuration ---
MAX_FIELD_LENGTH = 500
SENSITIVE_PATTERNS = [
    ".env", ".env.local", ".env.production", ".env.staging",
    "credentials", "secrets", "id_rsa", "id_ed25519",
    ".pem", ".key", "password", "token", "api_key", "apikey",
]
LOG_FOLDER = "_Agent Logs"
# Contents of the .gitignore dropped inside _Agent Logs/ on first use.
# Ignores all log files but keeps the .gitignore itself tracked so the rule
# travels with the repo.
LOG_GITIGNORE = "# Auto-generated by agent-logger.py — agent logs are ignored by default.\n*\n!.gitignore\n"


def truncate(value, max_len=MAX_FIELD_LENGTH):
    """Truncate a string value, adding ... if truncated."""
    if not isinstance(value, str):
        value = json.dumps(value, default=str)
    if len(value) > max_len:
        return value[:max_len] + "...[truncated]"
    return value


def is_sensitive(text):
    """Check if text references sensitive file patterns."""
    if not text:
        return False
    text_lower = text.lower()
    return any(p in text_lower for p in SENSITIVE_PATTERNS)


def get_project_dir(data):
    """Get the project directory from hook input data."""
    return data.get("cwd", os.getcwd())


def get_log_dir(project_dir):
    """Get the Agent Logs directory path."""
    return os.path.join(project_dir, "_Agent Logs")


def get_session_log_path(log_dir, session_id):
    """Get the session-specific log file path."""
    date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    short_id = session_id[:8] if session_id else "unknown"
    return os.path.join(log_dir, f"session-{date_str}-{short_id}.jsonl")


def get_index_path(log_dir):
    """Get the sessions index file path."""
    return os.path.join(log_dir, "sessions-index.jsonl")


def ensure_log_folder(project_dir):
    """Create _Agent Logs/ if it doesn't exist and drop a .gitignore inside it
    so log files are ignored by default in every project."""
    path = os.path.join(project_dir, LOG_FOLDER)
    os.makedirs(path, exist_ok=True)
    gitignore_path = os.path.join(path, ".gitignore")
    if not os.path.exists(gitignore_path):
        with open(gitignore_path, "w", encoding="utf-8") as f:
            f.write(LOG_GITIGNORE)


def write_log(log_path, entry):
    """Append a JSONL entry to the log file."""
    os.makedirs(os.path.dirname(log_path), exist_ok=True)
    with open(log_path, "a", encoding="utf-8") as f:
        f.write(json.dumps(entry, default=str) + "\n")


def summarize_tool_input(tool_name, tool_input):
    """Extract a human-readable summary from tool input."""
    if not tool_input:
        return ""

    if tool_name == "Bash":
        cmd = tool_input.get("command", "")
        return truncate(cmd, 200) if not is_sensitive(cmd) else "[sensitive command]"

    if tool_name in ("Write", "Edit"):
        fp = tool_input.get("file_path", "")
        if is_sensitive(fp):
            return f"[sensitive file: {os.path.basename(fp)}]"
        if tool_name == "Write":
            return f"write → {fp}"
        return f"edit → {fp}"

    if tool_name == "Read":
        fp = tool_input.get("file_path", "")
        if is_sensitive(fp):
            return f"[sensitive file: {os.path.basename(fp)}]"
        return f"read → {fp}"

    if tool_name in ("Glob", "Grep"):
        pattern = tool_input.get("pattern", "")
        return f"{tool_name.lower()} → {truncate(pattern, 100)}"

    if tool_name == "Task":
        desc = tool_input.get("description", "")
        agent_type = tool_input.get("subagent_type", "")
        return f"subagent({agent_type}) → {truncate(desc, 150)}"

    if tool_name == "WebSearch":
        return f"search → {truncate(tool_input.get('query', ''), 150)}"

    if tool_name == "WebFetch":
        return f"fetch → {truncate(tool_input.get('url', ''), 150)}"

    if tool_name.startswith("mcp__"):
        parts = tool_name.split("__")
        server = parts[1] if len(parts) > 1 else "unknown"
        tool = parts[2] if len(parts) > 2 else "unknown"
        return f"mcp({server}.{tool})"

    # Generic fallback
    return truncate(json.dumps(tool_input, default=str), 200)


def safe_tool_details(tool_name, tool_input):
    """Extract safe (non-sensitive) tool details for logging."""
    if not tool_input:
        return {}

    details = {}

    if tool_name == "Bash":
        cmd = tool_input.get("command", "")
        if not is_sensitive(cmd):
            details["command"] = truncate(cmd)
        details["timeout"] = tool_input.get("timeout")
        details["background"] = tool_input.get("run_in_background", False)

    elif tool_name in ("Write", "Edit"):
        fp = tool_input.get("file_path", "")
        details["file_path"] = fp if not is_sensitive(fp) else "[redacted]"
        # Never log file content
        if tool_name == "Edit":
            details["replace_all"] = tool_input.get("replace_all", False)

    elif tool_name == "Read":
        fp = tool_input.get("file_path", "")
        details["file_path"] = fp if not is_sensitive(fp) else "[redacted]"

    elif tool_name == "Task":
        details["subagent_type"] = tool_input.get("subagent_type", "")
        details["description"] = truncate(tool_input.get("description", ""), 200)
        details["model"] = tool_input.get("model")
        details["background"] = tool_input.get("run_in_background", False)

    elif tool_name in ("Glob", "Grep"):
        details["pattern"] = tool_input.get("pattern", "")
        details["path"] = tool_input.get("path", "")

    elif tool_name == "WebSearch":
        details["query"] = truncate(tool_input.get("query", ""), 200)

    elif tool_name == "WebFetch":
        details["url"] = truncate(tool_input.get("url", ""), 200)

    else:
        # Generic: log keys only, not values (safety)
        details["keys"] = list(tool_input.keys()) if isinstance(tool_input, dict) else []

    # Remove None values
    return {k: v for k, v in details.items() if v is not None}


# --- Event Handlers ---

def handle_session_start(data):
    project_dir = get_project_dir(data)
    ensure_log_folder(project_dir)

    log_dir = get_log_dir(project_dir)
    session_id = data.get("session_id", "unknown")
    log_path = get_session_log_path(log_dir, session_id)

    entry = {
        "ts": datetime.now(timezone.utc).isoformat(),
        "event": "SessionStart",
        "session_id": session_id,
        "source": data.get("source", ""),
        "model": data.get("model", ""),
        "cwd": project_dir,
        "permission_mode": data.get("permission_mode", ""),
    }
    write_log(log_path, entry)


def handle_user_prompt(data):
    project_dir = get_project_dir(data)
    log_dir = get_log_dir(project_dir)
    session_id = data.get("session_id", "unknown")
    log_path = get_session_log_path(log_dir, session_id)

    prompt = data.get("prompt", "")
    entry = {
        "ts": datetime.now(timezone.utc).isoformat(),
        "event": "UserPromptSubmit",
        "session_id": session_id,
        "prompt": truncate(prompt) if not is_sensitive(prompt) else "[redacted]",
    }
    write_log(log_path, entry)


def handle_pre_tool_use(data):
    project_dir = get_project_dir(data)
    log_dir = get_log_dir(project_dir)
    session_id = data.get("session_id", "unknown")
    log_path = get_session_log_path(log_dir, session_id)

    tool_name = data.get("tool_name", "unknown")
    tool_input = data.get("tool_input", {})

    entry = {
        "ts": datetime.now(timezone.utc).isoformat(),
        "event": "PreToolUse",
        "session_id": session_id,
        "tool": tool_name,
        "summary": summarize_tool_input(tool_name, tool_input),
        "details": safe_tool_details(tool_name, tool_input),
    }
    write_log(log_path, entry)


def handle_post_tool_use(data):
    project_dir = get_project_dir(data)
    log_dir = get_log_dir(project_dir)
    session_id = data.get("session_id", "unknown")
    log_path = get_session_log_path(log_dir, session_id)

    tool_name = data.get("tool_name", "unknown")
    tool_input = data.get("tool_input", {})

    entry = {
        "ts": datetime.now(timezone.utc).isoformat(),
        "event": "PostToolUse",
        "session_id": session_id,
        "tool": tool_name,
        "summary": summarize_tool_input(tool_name, tool_input),
        "status": "success",
    }
    write_log(log_path, entry)


def handle_post_tool_use_failure(data):
    project_dir = get_project_dir(data)
    log_dir = get_log_dir(project_dir)
    session_id = data.get("session_id", "unknown")
    log_path = get_session_log_path(log_dir, session_id)

    tool_name = data.get("tool_name", "unknown")
    error = data.get("error", "")

    entry = {
        "ts": datetime.now(timezone.utc).isoformat(),
        "event": "PostToolUseFailure",
        "session_id": session_id,
        "tool": tool_name,
        "error": truncate(error, 300),
        "is_interrupt": data.get("is_interrupt", False),
    }
    write_log(log_path, entry)


